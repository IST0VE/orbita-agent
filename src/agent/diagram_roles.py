"""
Конвейер разбора схем: кто за кем идёт и что видит.

Четыре этапа. На вход — одна схема draw.io, разобранная в данные (`drawio.py`);
на выходе — страница документации по ней, проверенная против самой схемы.

Роли расставлены так же, как в конвейере аналитики, и по той же причине: каждая
следующая работает с документом предыдущей, а не с сырым материалом заново.
Разница одна и она в начале: материал здесь не читает никто из ролей. Схему
разбирает код (`drawio_graph.source_node`), и все четверо получают один и тот же
разобранный JSON. Инструментов чтения файлов у них нет — и не должно быть:
единственный источник фактов обязан быть общим, иначе четыре специалиста
насчитают на схеме четыре разных набора стрелок.

Проверка достоверности тоже не роль. Ссылки на элементы схемы сверяются
арифметикой в `brief()` и уезжают ревьюеру готовым списком: платить модели за
сравнение двух списков строк незачем, а ошибается она на этом чаще, чем `set`.
"""

from __future__ import annotations

from agent import diagram_prompts, drawio
from agent.pipeline import Pipeline, Role, Stage

# Ключи в state["artifacts"], которые пишет не роль, а нода разбора схемы.
# Лежат там же, где документы этапов, потому что подставляются ровно так же —
# и потому что `Pipeline.done()` перебирает роли, а не ключи, и в страницы
# публикации эти два ключа не попадают.
DIAGRAM = "diagram"
IDS = "diagram_ids"

ROLES: tuple[Role, ...] = (
    Role(
        key="survey",
        number="01",
        title="Разбор схемы",
        summary="Что за система нарисована, её границы и основной поток",
    ),
    Role(
        key="components",
        number="02",
        title="Компоненты и интеграции",
        summary="Элементы, связи, хранилища и заметки со схемы — таблицами",
        needs=("survey",),
    ),
    Role(
        key="page",
        number="03",
        title="Страница документации",
        summary="Итоговая страница по шаблону: обзор, поток, таблицы, факты, вопросы",
        needs=("survey", "components"),
    ),
    Role(
        key="review",
        number="04",
        title="Ревью достоверности",
        summary="Каждое утверждение сверено со схемой, дефекты и финальная версия",
        needs=("survey", "components", "page"),
    ),
)

BY_KEY: dict[str, Role] = {role.key: role for role in ROLES}
KEYS: tuple[str, ...] = tuple(role.key for role in ROLES)

FIRST: Role = ROLES[0]
LAST: Role = ROLES[-1]


def prompt_for(key: str) -> str:
    """Системный префикс роли. База знаний сюда не подключена: справочника нет."""
    return diagram_prompts.for_role(key)


# --------------------------------------------------------------------------
# Сообщение роли
#
# Всё переменное — задача, схема, документы предыдущих этапов — уходит в
# human-сообщение, то есть в КОНЕЦ запроса. Префикс роли при этом не двигается
# ни на байт, и кеш провайдера засчитывает совпадение с прошлым вызовом.
#
# Данные схемы стоят перед документами этапов, а не после них: они одинаковы
# для всех четырёх ролей внутри треда, а документы копятся от этапа к этапу.
# Стабильное — ближе к началу, растущее — в хвост.
# --------------------------------------------------------------------------
TASK_TITLE = "Задача"
DIAGRAM_TITLE = "Данные схемы"
STAGE_TITLE = "Результат этапа"
CHECK_TITLE = "Автоматическая сверка ссылок"


def _check(page_text: str, known: str) -> str:
    """
    Сверка ссылок документа со схемой — без обращения к модели.

    Считается по последнему написанному документу, потому что именно он уедет
    в wiki. Список известных id приходит строкой: он собран нодой разбора из
    того же файла и не зависит от того, целиком ли данные схемы поместились
    в сообщение.
    """
    cited = drawio.cited_ids(page_text)
    if not cited:
        return (
            "В документе нет ни одной ссылки вида `[id: ...]`. Проверить его против схемы "
            "нельзя: считай это дефектом severity blocker и расставь ссылки в финальной версии."
        )

    ids = set(known.split())
    unknown = [value for value in cited if value not in ids]
    if not unknown:
        return (
            f"Ссылок в документе: {len(cited)}. Все указывают на существующие элементы схемы. "
            "Это не значит, что утверждения верны: проверь, что именно сказано про каждый."
        )
    return (
        f"Ссылок в документе: {len(cited)}, из них НЕ НАЙДЕНО на схеме: {len(unknown)}.\n"
        f"Несуществующие id: {', '.join(unknown)}.\n"
        "Каждое утверждение с такой ссылкой — выдуманный факт. Дефект severity blocker: "
        "убери утверждение или замени ссылку на настоящий элемент."
    )


def brief(role: Role, task: str, artifacts: dict | None) -> str:
    """Текст сообщения для роли: задача, схема, результаты этапов из `needs`."""
    artifacts = artifacts or {}
    diagram = (artifacts.get(DIAGRAM) or "").strip()

    parts = [f"# {TASK_TITLE}\n\n{task.strip()}"]
    parts.append(
        f"# {DIAGRAM_TITLE}\n\n```json\n{diagram}\n```"
        if diagram
        else f"# {DIAGRAM_TITLE}\n\nСхема не разобрана, данных нет."
    )

    for key in role.needs:
        text = (artifacts.get(key) or "").strip()
        source = BY_KEY[key]
        if text:
            parts.append(f"# {STAGE_TITLE} {source.number}. {source.title}\n\n{text}")
        else:
            # Этап мог не состояться: кончился бюджет, оператор остановил конвейер.
            # Молча отдать роли пустоту нельзя — она решит, что на схеме ничего
            # не нашлось, и напишет об этом как о свойстве схемы.
            parts.append(
                f"# {STAGE_TITLE} {source.number}. {source.title}\n\n"
                f"Этап не выполнен, результата нет. Работай по тому, что есть, "
                f"и прямо укажи в документе, чего тебе не хватило."
            )

    if role.key == "review":
        parts.append(
            f"# {CHECK_TITLE}\n\n"
            + _check(artifacts.get("page") or "", artifacts.get(IDS) or "")
        )

    return "\n\n".join(parts)


# Конвейер целиком — то, что получает граф.
PIPELINE = Pipeline(
    key="drawio",
    title="Документация схемы",
    summary="Схема draw.io превращается в проверенную страницу документации.",
    byline="конвейером разбора схем",
    roles=ROLES,
    prompt_for=prompt_for,
    brief=brief,
    # Папка без схемы разворачивается до первого вызова модели: четыре роли
    # напишут документацию по пустоте и возьмут за это деньги.
    admission=True,
    # Схему разбирает код, а не роль: адрес файла известен заранее, аргумент
    # у чтения ровно один, и все четыре этапа обязаны видеть один разбор.
    prelude=Stage(
        key="source",
        title="Разбор схемы",
        summary="Без вызова модели разбирает выбранный файл draw.io.",
    ),
)
