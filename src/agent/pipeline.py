"""
Форма конвейера: из чего он состоит и что общего у всех его сборок.

Конвейеров в проекте пять. Первый читает материалы проекта и выпускает
проектную документацию (`roles.py`), второй читает draw.io-схему и выпускает
описание системы по ней (`diagram_roles.py`), третий раскладывает готовый
документ аналитики на задачи и заводит их в трекере (`jira_roles.py`),
четвёртый читает задачу в Jira, ищет написанное в Confluence и выпускает
план, черновик задач и первичную документацию (`prep_roles.py`), пятый берёт
уже написанный пакет документов и сверяет его сам с собой (`audit_roles.py`).
Ролей у них разное число, префиксы у них свои, сообщение роли собирается
по-своему, источник данных у четвёртого свой — а порядок этапов, подстановка
результатов предыдущих, ворота бюджета, остановка оператором и публикация
постранично у них общие.

Поэтому здесь два типа данных и ни одной строки про конкретные роли. `Role` —
один этап, `Pipeline` — весь набор плюс два способа (как достать префикс роли и
как собрать ей сообщение) и набор инструментов. Дальше `graph.py` знает только
эти два типа: узлы, ворота и страницы порождаются из описания, а не из знания
о том, какой именно конвейер сейчас запущен. Шестой конвейер — это ещё один
`Pipeline`, а не ещё одна сборка графа.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass


@dataclass(frozen=True)
class Role:
    """Один этап конвейера."""

    # Ключ роли. Он же имя узла в графе, он же ключ в state["artifacts"],
    # он же ключ префикса в словаре промптов — чтобы связь между ними нельзя
    # было потерять переименованием в одном месте из трёх.
    key: str
    # Номер и название для документа и заголовка страницы.
    number: str
    title: str
    # Короткое пояснение: идёт в интерфейс и в шапку раздела.
    summary: str
    # Чьи результаты подставляются этой роли в конец сообщения, в этом порядке.
    needs: tuple[str, ...] = ()
    # Уходит ли роль в цикл с инструментами. Инструменты объявлены графу
    # всегда — иначе менялся бы префикс, — но переписку с ними ведут только
    # отмеченные роли. Имя историческое: сначала инструментами читались только
    # файлы задачи. Теперь ими же читаются Jira и Confluence, а смысл флага
    # прежний — «этой роли можно спрашивать, а не только отвечать».
    reads_files: bool = False


@dataclass(frozen=True)
class Stage:
    """
    Этап конвейера без вызова модели: прелюдия или постлюдия.

    Роль спрашивает модель, этап — нет. Материал добывается кодом (страница
    Confluence, тикет, разобранная схема), задачи заводятся кодом, и оба этих
    узла графу нужны так же, как роли: у них есть имя, заголовок и место
    в топологии. Отличие от `Role` одно и важное: у этапа нет префикса,
    потому что нет и запроса, — поэтому он и не `Role` с пустым промптом.

    Функция узла живёт в модуле графа и сюда не попадает: описание конвейера
    не должно знать, как ходить в Jira. Сюда попадает то, что нужно всем
    остальным, — под каким именем узел стоит в графе и как он называется
    на экране.
    """

    # Имя узла в графе. Оно же ключ в манифесте интерфейса — чтобы связь
    # между топологией и её подписью нельзя было потерять переименованием
    # в одном месте из двух.
    key: str
    title: str
    summary: str


@dataclass(frozen=True)
class Pipeline:
    """
    Набор ролей с их порядком: всё, что графу нужно знать о конвейере.

    `prompt_for` и `brief` — функции, а не методы: их пишет тот же модуль, что
    и роли, потому что обе целиком про содержание конвейера. Граф вызывает их,
    не заглядывая внутрь, и по этой границе проходит вся разница между
    конвейерами.
    """

    # Ключ конвейера: имя графа в `langgraph.json`, метка в логах и
    # `graph_id` манифеста интерфейса.
    key: str
    # Как конвейер называется и что делает — одной строкой каждое. Живёт здесь,
    # а не в манифесте интерфейса: манифест собирается из этого описания, и
    # второе место для названия рано или поздно разошлось бы с первым.
    title: str
    summary: str
    # Чем подписан собранный документ. В творительном падеже, потому что
    # уезжает в строку "Страница собрана автоматически <byline> <имя агента>".
    byline: str
    roles: tuple[Role, ...]
    # Системный префикс роли по её ключу. Именно он обязан быть побайтово
    # стабильным между вызовами — на нём держится весь учёт кеша.
    prompt_for: Callable[[str], str]
    # Сообщение роли: задача и результаты этапов из `needs`. Всё переменное —
    # и только оно — уезжает сюда, то есть в КОНЕЦ запроса.
    brief: Callable[[Role, str, dict], str]
    # Инструменты конвейера. Пустой набор означает файловые (`tools.FILE_TOOLS`):
    # так собраны три конвейера из четырёх, и переписывать их описания ради
    # явного повторения одного и того же значения смысла нет. Умолчание
    # подставляет граф — здесь его нет, потому что `tools.py` импортирует
    # роли, а не наоборот.
    #
    # Набор фиксирован для конвейера целиком: он уезжает в кешируемый префикс,
    # и роль, которой инструменты не привязали, послала бы запрос другой формы.
    tools: tuple = ()
    # Есть ли у конвейера проверка входа — отказ до первого вызова модели.
    # Саму проверку сборщик получает функцией: она смотрит в чужие системы
    # и в файловую систему, а описание конвейера про них знать не должно.
    # Здесь остаётся факт её существования: по нему манифест объявляет узел
    # `no_input`, а сборщик проверяет, что ему эту функцию действительно
    # передали, — иначе граф молча собрался бы без обещанной ветки.
    admission: bool = False
    # Этапы без вызова модели до первой роли и после последней. Функции узлов
    # передаются сборщику отдельно; здесь — имя и подпись.
    prelude: Stage | None = None
    postlude: Stage | None = None
    # Чем описан узел инструментов в интерфейсе. Сам узел заводится тогда и
    # только тогда, когда есть роль, которая в него ходит (`has_tools`), —
    # объявлять это вторым флагом значило бы дать им разойтись.
    tools_hint: str = "Безопасное чтение разрешённых файлов задачи."
    # Одна страница на прогон вместо страницы на этап.
    #
    # Постранично удобно, когда этапы читают разные люди и в разное время:
    # аналитик открывает свою страницу, ревьюер — свою. Конвейер подготовки
    # задачи так не читают. Его пять документов — это один разговор от тикета
    # до черновика документации, и человек, которому надо «посмотреть, что там
    # по задаче», получал пять страниц, четыре из которых закрывал не читая.
    one_page: bool = False

    @property
    def has_tools(self) -> bool:
        """Есть ли роль, которая ведёт переписку с инструментами."""
        return any(role.reads_files for role in self.roles)

    @property
    def first(self) -> Role:
        return self.roles[0]

    @property
    def last(self) -> Role:
        return self.roles[-1]

    @property
    def keys(self) -> tuple[str, ...]:
        return tuple(role.key for role in self.roles)

    def by_key(self, key: str) -> Role:
        for role in self.roles:
            if role.key == key:
                return role
        raise KeyError(f"неизвестная роль: {key!r}")

    def after(self, role: Role) -> Role | None:
        """Следующий этап конвейера. None — этот был последним."""
        index = self.roles.index(role) + 1
        return self.roles[index] if index < len(self.roles) else None

    def before(self, role: Role) -> Role | None:
        """Предыдущий этап. None — этот был первым."""
        index = self.roles.index(role) - 1
        return self.roles[index] if index >= 0 else None

    def done(self, artifacts: dict | None) -> list[Role]:
        """Роли, у которых уже есть непустой результат, в порядке конвейера."""
        artifacts = artifacts or {}
        return [role for role in self.roles if (artifacts.get(role.key) or "").strip()]

    def pending(self, artifacts: dict | None) -> list[Role]:
        """Роли, которые ещё не выпустили документ. Нужны сообщению об остановке."""
        finished = set(self.done(artifacts))
        return [role for role in self.roles if role not in finished]
