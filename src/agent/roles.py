"""
Конвейер ролей: кто за кем идёт и кто чей результат видит.

Пять этапов проектной аналитики. Каждый ведёт своя роль со своим системным
префиксом (`prompts.py`), каждый выпускает свой документ, и результат целиком
уезжает следующим по списку `needs`.

Почему конвейер описан данными, а не пятью почти одинаковыми функциями в графе:
роли отличаются ровно тремя вещами — префиксом, тем, чьи результаты им нужны,
и правом лезть в файлы. Всё остальное у них общее, и это общее должно быть
написано один раз. Добавить шестую роль — значит дописать сюда строку и завести
её префикс; узел, ворота бюджета, подстановка результатов и публикация
подхватятся сами.

Сама форма конвейера (`Role`, `Pipeline`) живёт в `pipeline.py`: конвейеров
в проекте два, и второй — разбор draw.io-схем (`diagram_roles.py`) — ездит по
тому же графу. Здесь остаётся только содержание этого конвейера.

Файлы задачи читает только аналитик. Так же устроен и оригинал на CrewAI, и это
не экономия на инструментах: следующие четверо работают с документом аналитика,
а не с сырыми материалами. Если каждый будет перечитывать записи встречи по-своему,
конвейер развалится на четыре независимых мнения, ради устранения которых он
и собран.
"""

from __future__ import annotations

from agent import config as cfg
from agent import prompts, tools
from agent.pipeline import Pipeline, Role

ROLES: tuple[Role, ...] = (
    Role(
        key="requirements",
        number="01",
        title="Системные требования",
        summary="Материалы задачи превращены в однозначные требования и state machine",
        reads_files=True,
    ),
    Role(
        key="api",
        number="02",
        title="Контракт API",
        summary="REST-контракт по требованиям: endpoints, ошибки, идемпотентность",
        needs=("requirements",),
    ),
    Role(
        key="data",
        number="03",
        title="Данные и события",
        summary="Хранение, обмен сообщениями, повторы и восстановление",
        needs=("requirements", "api"),
    ),
    Role(
        key="architecture",
        number="04",
        title="Архитектура решения",
        summary="Требования, API и данные сведены в одно решение без противоречий",
        needs=("requirements", "api", "data"),
    ),
    Role(
        key="review",
        number="05",
        title="Ревью и финальная версия",
        summary="Дефекты с severity и исправленная финальная спецификация",
        needs=("requirements", "api", "data", "architecture"),
    ),
)

BY_KEY: dict[str, Role] = {role.key: role for role in ROLES}
KEYS: tuple[str, ...] = tuple(role.key for role in ROLES)

FIRST: Role = ROLES[0]
LAST: Role = ROLES[-1]


def by_key(key: str) -> Role:
    return PIPELINE.by_key(key)


def after(role: Role) -> Role | None:
    """Следующий этап конвейера. None — этот был последним."""
    return PIPELINE.after(role)


def done(artifacts: dict | None) -> list[Role]:
    """Роли, у которых уже есть непустой результат, в порядке конвейера."""
    return PIPELINE.done(artifacts)


def prompt_for(key: str) -> str:
    """
    Системный префикс роли под текущий режим базы знаний.

    В режиме базы знаний справочные разделы уезжают из префикса в документы,
    а в промпте остаётся всё поведенческое. Выбор делается здесь, а не в узле
    графа: узлу незачем знать, из чего собран префикс, ему важно только, что
    внутри одного треда тот не меняется.
    """
    return prompts.core_prompt(key) if cfg.knowledge_enabled() else prompts.for_role(key)


# --------------------------------------------------------------------------
# Сообщение роли
#
# Всё переменное собрано здесь и уходит в human-сообщение — то есть в КОНЕЦ
# запроса. Префикс роли при этом не двигается ни на байт, и кеш провайдера
# продолжает засчитывать совпадение с прошлым вызовом.
#
# Обратный порядок («сначала материалы, потом задача») сэкономил бы одну
# строку и стоил бы всего кеша: любой результат предыдущего этапа сдвинул бы
# начало запроса, и каждый следующий этап оплачивался бы по полной цене.
# --------------------------------------------------------------------------
TASK_TITLE = "Задача"
STAGE_TITLE = "Результат этапа"


def brief(role: Role, task: str, artifacts: dict | None) -> str:
    """
    Текст сообщения для роли: задача и результаты этапов из `needs`.

    Результаты подставляются целиком, без сокращения. Пересказывать их своими
    словами было бы дешевле по токенам и бессмысленно по сути: ревьюер обязан
    видеть в точности то, что написал проектировщик, иначе он ревьюит пересказ.
    """
    artifacts = artifacts or {}
    parts = [f"# {TASK_TITLE}\n\n{task.strip()}"]

    for key in role.needs:
        text = (artifacts.get(key) or "").strip()
        source = by_key(key)
        if text:
            parts.append(f"# {STAGE_TITLE} {source.number}. {source.title}\n\n{text}")
        else:
            # Этап мог не состояться: кончился бюджет, оператор отклонил ход.
            # Молча отдать роли пустоту нельзя — она решит, что предыдущий
            # специалист ничего не нашёл, и напишет документ по несуществующим
            # требованиям, не сказав об этом ни слова.
            parts.append(
                f"# {STAGE_TITLE} {source.number}. {source.title}\n\n"
                f"Этап не выполнен, результата нет. Работай по тому, что есть, "
                f"и прямо укажи в документе, чего тебе не хватило."
            )

    return "\n\n".join(parts)


# Конвейер целиком — то, что получает граф. Всё, что выше, — его содержание.
PIPELINE = Pipeline(
    # `agent`, а не `analysis`: так этот граф называется в `langgraph.json`,
    # так его знает интерфейс и так лежат уже начатые треды. Имя историческое —
    # конвейер вырос из агента поддержки, — но ключ обязан совпадать с именем
    # графа, а не с тем, чем конвейер стал. Человеческое имя лежит в `title`.
    key="agent",
    title="Архитектурная аналитика",
    summary="Материалы задачи превращаются в требования, API, данные и архитектуру.",
    byline="конвейером проектной аналитики",
    roles=ROLES,
    prompt_for=prompt_for,
    brief=brief,
    tools=tuple(tools.RESEARCH_TOOLS),
    tools_hint="Файлы задачи, поиск и чтение страниц Confluence и задач Jira.",
)
