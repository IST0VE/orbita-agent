"""
Конвейер разбора схем draw.io: из .drawio — страница документации.

Второй граф проекта. Первый (`graph.py`) читает материалы проекта и пишет по ним
проектную документацию; этот читает одну схему и описывает нарисованную в ней
систему; третий (`jira_graph.py`) раскладывает готовую аналитику на задачи
и заводит их в трекере.
Ролей четыре (`diagram_roles.py`), и ездят они по тем же узлам: ворота
бюджета, остановка оператором, учёт кеша, публикация постранично — всё общее.
Разное только описание конвейера, и в этом смысл `pipeline.Pipeline`.

Граф:

  START -> context -> source -> survey -> gate_components -> components
                                       -> gate_page       -> page
                                       -> gate_review     -> review
        -> remember -> approve -> publish -> END

  START -> no_input -> remember      (в папке задачи нет схемы)

Что делает каждая нода:

  context    подставляет в конец задачи справку и память — как у остальных
             конвейеров. Список файлов задачи здесь тоже не лишний: схему
             выбирают из них, и имя, которого в папке нет, оператор увидит
             раньше модели;
  source     находит .drawio в папке задачи и разбирает его в данные
             (`drawio.py`). Без модели и без денег: XML разбирается кодом,
             и это не экономия, а условие достоверности — четыре роли обязаны
             видеть один и тот же набор стрелок, а не четыре своих;
  <роль>     вызов модели со стабильным префиксом этой роли. Первые несколько
             тысяч токенов префикса у всех четырёх побайтово одинаковы
             (`diagram_prompts.COMMON`), поэтому вторая и следующие роли
             попадают в кеш уже на первом своём вызове;
  gate_*     ворота перед этапом: бюджет и, если включено
             PIPELINE_REQUIRE_APPROVAL, подтверждение документа оператором;
  no_input   честный ответ вместо прогона: схемы нет, платить не за что;
  remember   запись в долгую память;
  approve    необязательная остановка перед публикацией;
  publish    четыре документа уезжают в цель из `publishers.py`.

Инструментов чтения файлов у ролей нет. В конвейере аналитики файлы читает
первая роль, потому что материалов много и заранее неизвестно, какие понадобятся;
здесь материал ровно один, он нужен целиком и всем сразу — читать его моделью
значило бы платить за вызов, который ничего не решает. Узла `tools` у этого
графа поэтому нет вообще: `graph.build_graph` заводит его только конвейеру,
в котором есть кому в него ходить.

Своей сборки графа у этого конвейера тоже больше нет. Она была: конвейер
писался раньше, чем общий сборщик научился проверке входа и узлу-прелюдии, и
полсотни строк рёбер жили здесь копией. Копия успела разойтись с оригиналом —
у графа не было ноды контекста, то есть ни справки, ни памяти, хотя `remember`
в конце в ту же память писал. Теперь сборка одна на все конвейеры, а разница
между ними — то, чем она и должна быть: описание ролей, проверка входа и
прелюдия.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from langchain_core.messages import AIMessage
from langchain_core.runnables import RunnableConfig
from langgraph.graph import StateGraph

from agent import config as cfg
from agent import diagram_roles, drawio, inputs, sources
from agent import graph as g

PIPELINE = diagram_roles.PIPELINE


class State(g.State, total=False):
    """Состояние треда плюс сводка по разобранной схеме."""

    # Что за файл прочитан и что в нём нашлось: имя, хеш, страницы, узлы, связи.
    # Перезаписывается целиком на каждом ходе — схема у треда одна, и величина
    # тут не накопительная. Ошибка разбора приезжает сюда же, ключом "error":
    # интерфейсу нужно показать причину, а маршруту — принять по ней решение.
    diagram: dict


class Options(g.Options, total=False):
    """Переопределения на тред: те же, что у конвейера аналитики, плюс схема."""

    # Имя файла схемы внутри папки задачи. Не задано — берётся первая найденная:
    # в папке обычно лежит одна схема, и заставлять оператора называть её
    # каждый раз незачем.
    diagram: str


# --------------------------------------------------------------------------
# Разбор схемы
#
# Единственное место, где решается, о какой схеме идёт речь: дальше все четыре
# роли видят уже разобранные данные и спорить о содержимом файла не могут.
# К диску отсюда ходят двое — проверка входа и сама нода, — и оба одной
# дорогой: `_parse()`. Второго способа выбрать файл в конвейере нет, иначе
# отказ на входе и разбор в ноде могли бы разойтись в том, что именно они
# прочитали.
# --------------------------------------------------------------------------
def _pick(task: str, wanted: str) -> Path:
    """Файл схемы: названный оператором или первый найденный в папке задачи."""
    if wanted:
        # Имя пришло из интерфейса — путь собирается только через inputs:
        # там же стоит единственная проверка на выход за пределы папки.
        path = inputs.resolve(task, wanted)
        if not drawio.is_diagram(path):
            raise drawio.DiagramError(f"{wanted!r}: это не файл draw.io")
        return path

    found = drawio.find(inputs.folder(task))
    if not found:
        raise drawio.DiagramError(
            "в папке задачи нет ни одного файла .drawio. Положите схему в папку "
            "и выберите её в интерфейсе или укажите имя файла в настройках прогона."
        )
    return found[0]


def _parse(task: str, wanted: str) -> dict:
    """Выбрать файл и разобрать его. Одна дорога для проверки входа и для ноды."""
    path = _pick(task, wanted)
    return drawio.parse(path, name=_relative(path, task))


def source_node(state: State, config: RunnableConfig) -> dict:
    """
    Найти схему, разобрать её и положить в состояние.

    Данные схемы кладутся в `artifacts` рядом с документами этапов, хотя роль
    их не писала. Так они попадают в сообщение каждой роли тем же способом, что
    и результаты предыдущих этапов (`diagram_roles.brief`), и не требуют ни
    отдельного канала в состоянии, ни особого случая в узле роли.

    Отдельно от данных сохраняется список идентификаторов: по нему ревьюеру
    считается сверка ссылок. Он нужен целым даже тогда, когда сами данные
    не поместились в потолок и приехали обрезанными.
    """
    task = sources.task_dir(config)
    wanted = str(g.options(config).get("diagram") or "")
    question = sources.question_of(state)

    try:
        data = _parse(task, wanted)
    except (drawio.DiagramError, inputs.InputError, OSError) as exc:
        # Разбор не состоялся — это нормальный исход, а не падение треда:
        # оператор мог выбрать не ту папку. До первого хода такую папку
        # заворачивает проверка входа (`missing_diagram`), и сюда остаётся
        # редкое: файл убрали между проверкой и разбором либо схема перестала
        # читаться на следующем ходе треда. Конвейер от этого не падает —
        # причина уходит оператору сообщением, а роли получат честное
        # «схема не разобрана, данных нет» (`diagram_roles.brief`).
        return {
            "task": question,
            "diagram": {"error": str(exc)},
            "messages": [AIMessage(content=f"Разбор схемы не выполнен: {exc}")],
            "stage": "source",
        }

    stats = drawio.stats(data)
    return {
        "task": question,
        "diagram": stats,
        "artifacts": {
            diagram_roles.DIAGRAM: drawio.as_json(data, cfg.diagram_max_chars()),
            diagram_roles.IDS: " ".join(sorted(drawio.ids(data))),
        },
        "messages": [AIMessage(content=_note(stats))],
        "stage": "source",
    }


def _relative(path: Path, task: str) -> str:
    """Имя файла для документа: путь от папки задачи, а не от корня диска."""
    try:
        return path.relative_to(inputs.folder(task)).as_posix()
    except (ValueError, inputs.InputError):
        return path.name


def _note(stats: dict) -> str:
    """Что прочитано — оператору в тред. Ход по графу должен быть виден."""
    return (
        f"Разобрана схема `{stats['name']}` (версия `{stats['sha256'][:12]}`): "
        f"страниц {stats['pages']}, элементов {stats['nodes']}, связей {stats['edges']}, "
        f"из них полных {stats['complete_edges']}. "
        f"Факты в документе будут строиться только по полным связям; "
        f"оборванных {stats['incomplete_edges']} — они уйдут в вопросы к автору схемы."
    )


def missing_diagram(state: State, config: RunnableConfig) -> str:
    """
    Причина не начинать прогон, или пустая строка.

    Условие ровно одно: состоится ли разбор схемы. Отвечает на это проверка
    единственным честным способом — разбирая. Файла может не быть, файл может
    оказаться не схемой, схема может не читаться, и разница между этими тремя
    случаями для оператора важна, а угадать её по имени файла нельзя.

    Разбор при этом делается дважды: здесь и в ноде `source`. Это осознанно.
    Он идёт по локальному файлу, стоит миллисекунды и ноль токенов, а
    альтернатива — узнать о нечитаемой схеме после четырёх оплаченных вызовов
    модели, каждый из которых напишет документ по пустоте. Раньше эту ветку
    держал свой узел `no_source` и своя сборка графа; проверка входа делает то
    же самое тем же способом, что у конвейеров декомпозиции и подготовки.

    Следующий ход уже начатого треда проверку проходит без обращения к диску:
    схема разобрана на прошлом ходе и лежит в артефактах.
    """
    if state.get("artifacts"):
        return ""

    chosen = g.options(config)
    try:
        _parse(sources.task_dir(config), str(chosen.get("diagram") or ""))
    except (drawio.DiagramError, inputs.InputError, OSError) as exc:
        return (
            f"Разбор схемы не выполнен: {exc}. Прогон остановлен до первого "
            "вызова модели — деньги не потрачены."
        )
    return ""


def build_graph(llm: Any = None) -> StateGraph:
    """
    Собрать конвейер по описанию из `diagram_roles.py`.

    Сборка общая (`graph.build_graph`); своей у этого конвейера нет и не должно
    быть — в этом смысл `pipeline.Pipeline`. Отличий от конвейера аналитики
    три, и все три передаются параметрами: другое описание ролей, своя проверка
    входа и узел разбора схемы между контекстом и первой ролью. Пятая роль
    добавляется строкой в `diagram_roles.ROLES` и своим префиксом в
    `diagram_prompts.ROLE_PROMPTS`; здесь не меняется ничего.

    Узел разбора стоит прелюдией, а не первой ролью: адрес файла известен
    заранее, аргумент у чтения ровно один, и просить модель позвать инструмент
    с уже известным аргументом — оплаченный вызов, который ничего не выбирает.

    state_schema и options_schema обязательны: без них LangGraph выбросит из
    обновления `diagram` и не увидит выбранный оператором файл.

    llm — готовая модель вместо собранной из окружения. Нужна тестам, чтобы
    прогнать граф целиком на подделке, без ключа и без сети.
    """
    return g.build_graph(
        llm=llm,
        pipeline=PIPELINE,
        admission=missing_diagram,
        prelude=source_node,
        state_schema=State,
        options_schema=Options,
    )


# Для Studio / langgraph dev: компилируем БЕЗ чекпоинтера, как и остальные графы.
graph = build_graph().compile()
