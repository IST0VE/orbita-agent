"""
Стабильные системные префиксы конвейера сверки пакета.

Три роли, и у всех трёх одна особенность: они ничего не проектируют. Пакет уже
написан, и задача этого конвейера — сказать, что в нём не сходится, а не
дописать недостающее. Роль, которая вместо находки выдаёт исправленный текст,
делает хуже: расхождение исчезает из отчёта, но остаётся в документах, потому
что менять их этот конвейер не уполномочен.

Поэтому в общем блоке отдельным правилом записано, что находка без ссылки на
документ — это не находка. Сверку читают, чтобы пойти и поправить; отчёт, по
которому непонятно, куда идти, стоит ровно столько же, сколько его не было.

Часть работы уже сделана кодом (`checks.py`), и её результат приезжает ролям
разделом «Автоматическая сверка». Переписывать его своими словами запрещено
прямо в промпте: пересказ арифметики моделью — это оплаченный вызов, который
портит точные числа.
"""

