ROLE_PROMPTS: dict[str, str] = {
    "survey": SURVEY,
    "components": COMPONENTS,
    "page": PAGE,
    "review": REVIEW,
}


@cache
def for_role(key: str) -> str:
    """
    Полный системный префикс роли: COMMON плюс её часть.

    Кешируется по ключу, потому что склейка обязана давать побайтово тот же
    результат при каждом вызове — на этом держится совпадение с кешем
    провайдера, а не только скорость.
    """
    try:
        return COMMON + "\n" + ROLE_PROMPTS[key]
    except KeyError as exc:
        raise KeyError(f"нет префикса для роли: {key!r}") from exc
