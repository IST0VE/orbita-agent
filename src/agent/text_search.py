"""
Условие полнотекстового поиска для Jira и Confluence: слова запроса и их основы.

Поиск обоих трекеров сопоставляет слова буквально, если индекс не настроен на
русский язык: «паролю» не находит страницу про «пароль», а фраза из пяти слов
требует все пять. 27 сентября 2026 роль поиска конвейера подготовки задала
Confluence тринадцать запросов. Все пять пустых были фразами в три–шесть слов
(«правила формирования пароля пользователя»), а однословный `htusers` нашёл
ровно нужную страницу.

Поэтому к запросу как есть добавляется второе условие: те же значимые слова,
но основами с усечением (`парол*`). Префиксный запрос находит все формы слова
при любом языке индекса: без русского анализатора в индексе лежат целые слова,
с ним — их основы, и префикс совпадает с обоими. Слова соединяются через AND:
запрос остаётся запросом про одну тему, а не про любое из слов.

Основа получается срезанием окончания, а не словарём. Словаря в проекте нет,
а ошибка здесь дешёвая: лишняя страница в пяти найденных, а не потерянная.
Латиница и идентификаторы (`nginx`, `gslb-user-mgmt`) не трогаются: у имени
утилиты окончаний нет, и усечение превратило бы точное имя в чужие совпадения.
"""

from __future__ import annotations

import re
from collections.abc import Callable

_WORD = re.compile(r"[0-9A-Za-zА-Яа-яЁё_][0-9A-Za-zА-Яа-яЁё_.\-]*")
_CYRILLIC = re.compile(r"[А-Яа-яЁё]+")

#: Служебные слова: в индексе их нет или они есть на каждой странице.
STOP_WORDS = frozenset(
    """
    а без в во вне для до же за и из или как ко ли на над не ни но о об обо от по
    под при про с со то у через что это эти его её их все всё так там тут где
    the a an of to in on for and or with by from at is are
    """.split()
)

# Окончания от длинных к коротким: срезается самое длинное совпавшее.
_ENDINGS = tuple(
    sorted(
        """
        иями ями ами ией иях ах ях ам ям ом ем ой ей ий ый ая яя ое ее ые ие ых их
        ов ев ию ью ия ья ье ии ьи у ю а я о е ы и ь й
        """.split(),
        key=len,
        reverse=True,
    )
)

#: Короче этого основа перестаёт что-то значить: `рол*` находит и «роль», и «ролик».
MIN_STEM = 4

#: Сколько значимых слов идёт во второе условие. Больше — запрос уже не про одну тему.
MAX_WORDS = 5


def words(query: str) -> list[str]:
    """Значимые слова запроса в исходном порядке, без повторов и служебных."""
    seen: dict[str, None] = {}
    for match in _WORD.finditer(query or ""):
        word = match.group(0).strip(".-")
        if len(word) < 2 or word.lower() in STOP_WORDS:
            continue
        seen.setdefault(word, None)
    return list(seen)


def stem(word: str) -> str:
    """
    Основа слова с усечением или само слово.

    Усекаются только слова целиком на кириллице и не короче пяти букв:
    у четырёхбуквенного слова основа выходит короче `MIN_STEM`, а латиница —
    это чаще всего имя, и оно ищется как есть.
    """
    if len(word) < MIN_STEM + 1 or not _CYRILLIC.fullmatch(word):
        return word
    lowered = word.lower()
    for ending in _ENDINGS:
        if lowered.endswith(ending) and len(lowered) - len(ending) >= MIN_STEM:
            return lowered[: -len(ending)] + "*"
    return lowered + "*"


def condition(query: str, escape: Callable[[str], str], field: str = "text") -> str:
    """
    Условие `field ~` для CQL или JQL: запрос как есть ИЛИ все его основы.

    Запрос как есть остаётся первым: он сохраняет всё, что поиск умел раньше, —
    точную фразу, имя с дефисами, синтаксис самого трекера. Второе условие
    добавляется, только если оно отличается от первого: однословный латинский
    запрос уходит без изменений.
    """
    text = (query or "").strip()
    exact = f'{field} ~ "{escape(text)}"'
    stems = [stem(word) for word in words(text)[:MAX_WORDS]]
    if not stems or (len(stems) == 1 and stems[0] == text):
        return exact
    broad = " AND ".join(f'{field} ~ "{escape(item)}"' for item in stems)
    return f"({exact} OR ({broad}))"
