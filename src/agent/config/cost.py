# --------------------------------------------------------------------------
# Цены, $ за 1M токенов
#
# Значения по умолчанию — deepseek-v4-flash на момент написания. Тарифы
# меняются регулярно, а при смене провайдера меняются целиком — это ровно тот
# случай, когда правка не должна требовать коммита: сверились с прайсом
# провайдера, вписали в .env.
# --------------------------------------------------------------------------
def price_per_mtok() -> dict:
    """
    Цена на каждый счётчик: сначала таблица `costmeter/prices.toml` по паре
    (провайдер, модель), поверх — переменные `PRICE_*`, если заданы.

    Три переменные хороши ровно для одной модели: у каждой свой тариф, и при
    смене `LLM_MODEL` их пришлось бы переписывать руками. Таблица снимает эту
    работу, а переменные остаются как переопределение — для стенда, скидки
    или свежего прайса, до которого не дошли руки.

    Модели нет в таблице и переменные не заданы — `costmeter` предупредит,
    а стоимость будет нулевой. Это лучше молчаливого неверного счёта.
    """
    return price_info().per_counter()


def price_info():
    """
    Тариф целиком: числа, источник, версия и признак полноты.

    Нужен там, где решение зависит не от цены, а от того, есть ли она вообще:
    денежные ворота, состояние треда, интерфейс. `price_per_mtok()` отвечает
    только числами и на вопрос «а известны ли они» ответить не может.
    """
    return prices.for_model(llm_provider(), model_name())


#: block — без тарифа денежный лимит не пропускает вызов; allow — лимит явно
#: объявлен неприменимым к этому прогону.
BUDGET_UNKNOWN_PRICE_MODES = ("block", "allow")


def budget_unknown_price() -> str:
    """
    Что делать с денежным лимитом, когда тарифа нет: `block` или `allow`.

    Неизвестный тариф давал ноль, ноль всегда меньше лимита, и денежные ворота
    пропускали каждый следующий вызов. Формально лимит был включён; фактически
    его не было. Поэтому по умолчанию — отказ: либо тариф, либо явно
    объявленный режим без денежного контроля.

    `allow` не «считать по нулю»: он означает, что денежный лимит к этому
    прогону не применяется, и это видно в состоянии и в сообщении оператору.
    Ограничения на количество шагов и на историю остаются в силе в обоих
    режимах — они не про деньги.
    """
    mode = env_str("BUDGET_UNKNOWN_PRICE", "block").lower()
    if mode not in BUDGET_UNKNOWN_PRICE_MODES:
        raise ConfigError(
            f"BUDGET_UNKNOWN_PRICE={mode!r}: поддерживаются "
            + ", ".join(BUDGET_UNKNOWN_PRICE_MODES)
        )
    return mode


def budget_usd_per_thread() -> float:
    """
    Потолок расхода на один тред в долларах. 0 — без потолка (по умолчанию).

    Учёт, который только отчитывается постфактум, — половина ценности. Вторая
    половина: при превышении граф уходит в конец с честным сообщением вместо
    следующего вызова модели.
    """
    return env_float("BUDGET_USD_PER_THREAD", 0.0, minimum=0.0)


def tool_turns_per_run() -> int:
    """
    Сколько раз за прогон роль может сходить в инструменты. 0 — без потолка.

    Роль с инструментами ведёт переписку, и решение «спросить ещё раз»
    принимает модель. Ворота бюджета этот цикл ограничивают, но они выключены
    по умолчанию (BUDGET_USD_PER_THREAD=0), и тогда у петли не остаётся
    тормоза вообще: она упирается в recursion_limit LangGraph — около десяти
    тысяч шагов, то есть тысячи оплаченных вызовов, — и обрывается ошибкой
    мимо ветки, которая публикует сделанное.

    Поэтому потолок здесь свой, независимый от денег, и включён по умолчанию.
    Исчерпав его, роль делает последний ход без инструментов и пишет документ
    по тому, что успела прочитать, — так же, как последний ход расследования
    в конвейере НТ.
    """
    return env_int("TOOL_TURNS_PER_RUN", 12, minimum=0)
