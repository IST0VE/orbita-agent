"""
Состояние конвейера: что копится между узлами и что можно задать на тред.

Модуль отделён от графа по одной причине: состояние читают все, а собирает
граф. Схему видят ноды, маршруты, сборка, три соседних конвейера со своими
полями (`jira_graph.State` и другие наследуются отсюда) и тесты. Держать её
в одном файле с фабриками узлов значило заставлять каждого из них тянуть
за собой весь граф.

Два редьюсера и ни одного лишнего. Счётчики токенов складываются, документы
этапов сливаются словарём — всё остальное состояние LangGraph заменяет
последним значением, и это правильное поведение: у стадии, задачи и остановки
нет истории, у них есть текущее значение.
"""

from __future__ import annotations

from typing import Annotated, Any, TypedDict

from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages

USAGE_KEYS = ("cache_hit", "cache_miss", "cache_write", "output", "calls")


def _is_number(value: Any) -> bool:
    """bool — подкласс int, но складывать True с True здесь бессмысленно."""
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _merge_usage(old: dict | None, new: dict | None) -> dict:
    """
    Редьюсер: складывает счётчики токенов по всем вызовам LLM в треде.

    Ключи объединяются, а не берутся из фиксированного списка: провайдер или
    следующая версия langchain может принести свой счётчик, и терять его не
    хочется. Обратная сторона — в usage может приехать нечисловое поле
    (строка с именем модели, словарь с деталями), на котором сложение упало бы.
    Такие ключи не суммируются: побеждает последнее записанное значение.
    """
    old = old or dict.fromkeys(USAGE_KEYS, 0)
    if not new:
        return old

    merged: dict = {}
    for key in set(old) | set(new):
        before, after = old.get(key, 0), new.get(key, 0)
        if _is_number(before) and _is_number(after):
            merged[key] = before + after
        else:
            merged[key] = new.get(key, old.get(key))
    return merged


def _merge_artifacts(old: dict | None, new: dict | None) -> dict:
    """
    Редьюсер результатов этапов: `{ключ роли: текст документа}`.

    Обновление, а не замена: узел роли возвращает только свой ключ и не обязан
    знать, что уже лежит в состоянии. Повторный прогон той же роли в том же
    треде перезаписывает её документ — версия всегда последняя, накапливать
    черновики незачем.
    """
    merged = dict(old or {})
    merged.update(new or {})
    return merged


class State(TypedDict, total=False):
    messages: Annotated[list[AnyMessage], add_messages]
    usage: Annotated[dict, _merge_usage]
    # Задача конвейера: текст оператора без подставленного контекста. Пишется
    # нодой контекста один раз за ход и дальше читается каждой ролью — иначе
    # каждая заново вычленяла бы её из истории сообщений, по-своему.
    task: str
    # Готовые документы этапов. Ключ — `roles.Role.key`.
    artifacts: Annotated[dict, _merge_artifacts]
    # Ключ роли, которая отработала последней. Нужен интерфейсу: по нему видно,
    # где конвейер сейчас и на чём он остановился.
    stage: str
    # Решение оператора на воротах этапа: {"stage": ключ, "reason": текст}.
    # Заполнено — конвейер дальше не идёт. Пишется воротами, читается их же
    # роутером и нодой `halted`.
    halt: dict
    # Итоговая документация в storage-формате Confluence и результат её публикации.
    # Оба поля перезаписываются целиком на каждом ходе: страница в Confluence одна
    # на тред, и содержимое у неё всегда актуальное, а не накопленное.
    document: str
    publication: dict
    # Хеш тела последней *опубликованной* версии — по нему режим `changed`
    # решает, идти ли в сеть. Обновляется только после успешной публикации,
    # иначе сравнивать было бы не с чем.
    document_hash: str
    # Решение оператора по текущему ходу: {"decision": "approved" | "rejected"}.
    # Пишется нодой `approve` и перечитывается нодой `publish`; на следующем
    # ходе спрашивают заново, поэтому поле перезаписывается целиком.
    approval: dict
    # Те же счётчики, что в usage, но в деньгах по текущему тарифу. Считается
    # на сервере (см. `cost_summary`) и перезаписывается целиком: величина
    # накопительная, складывать нечего.
    cost: dict


class Options(TypedDict, total=False):
    """
    Что можно переопределить на тред через `configurable` (или `context`).

    Модель задаётся только серверной LLM_MODEL. Старые значения `model`
    в конфигурации треда игнорируются функцией runtime.options().
    """

    provider: str
    temperature: float
    publish: bool
    # Папка задачи внутри AGENT_INPUT_DIR: её файлы попадают в список в конце
    # вопроса, и только их видят инструменты чтения. Свойство хода, а не
    # процесса: у соседнего треда своя задача и свои файлы.
    input_dir: str
    # Файл или файлы внутри этой папки — источник задачи вместо всей папки.
    #
    # Пусто — материалом считается вся папка, и так было всегда. Но папка
    # задачи это не всегда однородный материал: в ней лежит и аналитика, и
    # протокол встречи, и выгрузка, а разложить на задачи надо один документ.
    # Сказать об этом можно было только словами в запросе — «разложи файл
    # аналитика.md», — и конвейер декомпозиции искал это имя подстрокой в
    # тексте оператора. Теперь выбор делается в интерфейсе и приезжает сюда.
    #
    # Что значит выбор, решает конвейер. Там, где документ и есть вход
    # (`jira_graph`), читается ровно он. Там, где файлы читают инструменты
    # (`graph`, `prep_graph`), выбор уезжает в список файлов пометкой: роль
    # видит, с чего начинать, но соседний файл ей не запрещён — материал там
    # разнородный, и запрет стоил бы дороже подсказки.
    #
    # Строка или список: аналитика редко живёт одним файлом, и комплект
    # документации выбирается целиком. Разбирает оба вида `inputs.picked_names`.
    input_file: str | list[str]
