"""
Стабильные системные префиксы конвейера декомпозиции в Jira.

Четыре роли, и последняя отличается от трёх остальных адресатом. Первые три
пишут для людей: карту читают на refinement, backlog — команда, ревью —
тимлид. Четвёртая пишет для кода: её блок в тройных кавычках с пометкой json
разбирает `jira_plan.py`, и по нему заводятся настоящие задачи. Поэтому её
промпт — единственный, где формат описан по полям и где сказано, что после
закрывающего блока писать нечего: всё, что модель добавит от себя, либо не
разберётся, либо уедет в чужой трекер.
"""

